#!/usr/bin/env node
// Rerunnable, zero-npm-dep sound-effect synthesizer for DJ Supermercado's
// FX pad (src/lib/fx.ts) — Milestone 4 Part C, extended with laser + brake
// (the FX-upgrade milestone), then superseded for five of its six clips by
// the real-SFX swap (see the NOTE above DEFAULT_CLIPS below). Synthesizes
// short PCM clips in plain JS (Node built-ins only), wraps each in a
// hand-rolled 44-byte canonical WAV header, writes a temp .wav, then shells
// out to the system `ffmpeg` (confirmed on PATH in this environment) to
// convert to mp3 into public/sfx/. This script IS the source of riser.mp3 —
// its output is committed to git so the app doesn't need ffmpeg (or this
// script) at build/runtime.
//
// By default this only writes riser.mp3 — see the NOTE above DEFAULT_CLIPS
// below for why the five real-recording-replaced clips are no longer
// regenerated by default (or even under a flag short of the explicit
// OVERWRITE_REAL_SFX_WITH_SYNTH=1 opt-in).
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const SAMPLE_RATE = 44100;
const OUT_DIR = fileURLToPath(new URL("../public/sfx/", import.meta.url));

// --- hand-rolled canonical 44-byte WAV header (mono, 16-bit PCM) ---
function wavHeader(dataLength, sampleRate = SAMPLE_RATE, numChannels = 1, bitsPerSample = 16) {
  const blockAlign = numChannels * (bitsPerSample / 8);
  const byteRate = sampleRate * blockAlign;
  const buffer = Buffer.alloc(44);
  buffer.write("RIFF", 0);
  buffer.writeUInt32LE(36 + dataLength, 4);
  buffer.write("WAVE", 8);
  buffer.write("fmt ", 12);
  buffer.writeUInt32LE(16, 16); // PCM fmt chunk size
  buffer.writeUInt16LE(1, 20); // audio format 1 = PCM
  buffer.writeUInt16LE(numChannels, 22);
  buffer.writeUInt32LE(sampleRate, 24);
  buffer.writeUInt32LE(byteRate, 28);
  buffer.writeUInt16LE(blockAlign, 32);
  buffer.writeUInt16LE(bitsPerSample, 34);
  buffer.write("data", 36);
  buffer.writeUInt32LE(dataLength, 40);
  return buffer;
}

function toWavBuffer(samples) {
  const data = Buffer.alloc(samples.length * 2);
  for (let i = 0; i < samples.length; i++) {
    const s = Math.max(-1, Math.min(1, samples[i]));
    data.writeInt16LE(Math.round(s * 32767), i * 2);
  }
  return Buffer.concat([wavHeader(data.length), data]);
}

function samplesFor(seconds, fn) {
  const n = Math.round(seconds * SAMPLE_RATE);
  const out = new Float32Array(n);
  const dt = 1 / SAMPLE_RATE;
  for (let i = 0; i < n; i++) out[i] = fn(i * dt, i, n);
  return out;
}

// --- airhorn: two slightly-detuned saw waves (415/440Hz) + vibrato + fast attack, ~1.2s ---
function sawWave(phase) {
  // phase in cycles (not radians) -> ramp -1..1. Fine for a short bright
  // stinger; the aliasing a naive saw introduces is inaudible under this
  // fast attack/short clip.
  return 2 * (phase - Math.floor(phase + 0.5));
}

function makeAirhorn() {
  const duration = 1.2;
  const f1 = 415;
  const f2 = 440;
  const vibratoHz = 6;
  const vibratoDepthHz = 4;
  const attack = 0.01;
  let phase1 = 0;
  let phase2 = 0;
  const dt = 1 / SAMPLE_RATE;
  return samplesFor(duration, (t) => {
    const vibrato = vibratoDepthHz * Math.sin(2 * Math.PI * vibratoHz * t);
    phase1 += (f1 + vibrato) * dt;
    phase2 += (f2 + vibrato) * dt;
    const env = t < attack ? t / attack : Math.exp(-1.2 * (t - attack));
    return 0.5 * env * (sawWave(phase1) + sawWave(phase2)) * 0.5;
  });
}

// --- siren: sine sweep 600<->1200Hz, two full cycles over ~2s ---
function makeSiren() {
  const duration = 2.0;
  const center = 900;
  const amplitude = 300; // 600..1200Hz
  const sweepHz = 1; // 1 full up/down cycle per second -> 2 cycles over 2s
  let phase = 0;
  const dt = 1 / SAMPLE_RATE;
  return samplesFor(duration, (t) => {
    const freq = center + amplitude * Math.sin(2 * Math.PI * sweepHz * t);
    phase += freq * dt;
    return 0.6 * Math.sin(2 * Math.PI * phase);
  });
}

// --- riser: white noise through a highpass sweeping ~200Hz -> ~8kHz, rising volume envelope, ~4s ---
// No Web Audio available in Node, so the "sweeping highpass" is a simple
// one-pole (first-order RC) highpass filter applied per-sample with a
// time-varying cutoff, rather than an FFT/convolution approach — crude but
// audibly effective for a short percussive texture like this.
function makeRiser() {
  const duration = 4.0;
  const dt = 1 / SAMPLE_RATE;
  let prevX = 0;
  let prevY = 0;
  return samplesFor(duration, (t) => {
    const x = Math.random() * 2 - 1;
    const fc = 200 * Math.pow(8000 / 200, t / duration); // exponential cutoff sweep
    const rc = 1 / (2 * Math.PI * fc);
    const alpha = rc / (rc + dt);
    const y = alpha * (prevY + x - prevX);
    prevX = x;
    prevY = y;
    const envelope = Math.pow(t / duration, 1.5); // rising, accelerating toward the end
    return 0.8 * y * envelope;
  });
}

// --- rewind: bright tone, rapid exponential pitch-down "spindown" + fast shallow flutter, ~1.2s ---
function makeRewind() {
  const duration = 1.2;
  const startFreq = 2200;
  const endFreq = 80;
  const flutterHz = 18;
  const flutterDepthHz = 15;
  let phase = 0;
  const dt = 1 / SAMPLE_RATE;
  return samplesFor(duration, (t) => {
    const base = startFreq * Math.pow(endFreq / startFreq, t / duration); // exponential spindown
    const flutter = flutterDepthHz * Math.sin(2 * Math.PI * flutterHz * t);
    const freq = Math.max(20, base + flutter);
    phase += freq * dt;
    const envelope = Math.min(1, t / 0.02) * Math.exp(-0.5 * t); // fast attack, gentle decay
    return 0.6 * envelope * Math.sin(2 * Math.PI * phase);
  });
}

// --- laser: short sharp descending zap/hit, <0.5s, punchy — genre-lane
// variation on airhorn/siren so El Cerebro isn't stuck repeating the same
// stinger twice in a row (reggaeton/cubaton/dancehall/hip-hop lane) ---
function makeLaser() {
  const duration = 0.35;
  const startFreq = 3000;
  const endFreq = 300;
  let phase = 0;
  const dt = 1 / SAMPLE_RATE;
  return samplesFor(duration, (t) => {
    const freq = startFreq * Math.pow(endFreq / startFreq, t / duration); // exponential descending sweep
    phase += freq * dt;
    const envelope = Math.min(1, t / 0.005) * Math.exp(-6 * t); // near-instant attack, fast decay -> punchy hit
    return 0.7 * envelope * sawWave(phase); // saw (not sine) for the brighter "zap" edge
  });
}

// --- brake: vinyl-brake decelerating pitch-down to full stop, ~0.8s.
// Reuses makeRewind's exponential pitch-down approach, but shorter and
// harder (faster decay, no flutter) — a hard stop, not rewind's spin. ---
function makeBrake() {
  const duration = 0.8;
  const startFreq = 1800;
  const endFreq = 30;
  let phase = 0;
  const dt = 1 / SAMPLE_RATE;
  return samplesFor(duration, (t) => {
    const freq = Math.max(15, startFreq * Math.pow(endFreq / startFreq, t / duration)); // exponential pitch-down, no flutter
    phase += freq * dt;
    const envelope = Math.min(1, t / 0.01) * Math.exp(-1.1 * t); // fast attack, harder/shorter decay than rewind
    return 0.65 * envelope * Math.sin(2 * Math.PI * phase);
  });
}

