#!/usr/bin/env node
// M8.1m — re-key every Drive-ID-keyed data file from the OLD crate folder to the
// NEW v2 folder (trimmed audio + stems).
//
// WHY THIS IS NEEDED AT ALL. Every data file in src/data is keyed by Google Drive
// file id, and a new folder means every file gets a new id. Without this step the
// app would list the v2 folder and find that not one track has tags, loop points,
// vocal maps or stems - all of that would look like it had never been generated.
//
// HOW IT WORKS. Names are the join key: the v2 folder was uploaded from the same
// filenames, so old-name -> old-id and new-name -> new-id give old-id -> new-id.
// That map is applied to:
//   loop-points-trimmed.json, vocal-maps-trimmed.json, cue-suggestions-trimmed.json
//     (keyed "drive:<id>")            -> *-v2.json
//   stem-manifest.json (keyed <id>, values are LOCAL paths)
//     -> stem-manifest-v2.json where each stem's value becomes its Drive file id
//        under the v2 folder's stems/ subfolder. This is what makes stem_migrate
//        stop refusing (page.tsx's stemEntryFor treats a "/" in the value as
//        "not on Drive yet").
//
// It does NOT touch crate-manifest.json - that is regenerated by
// make:crate-manifest against the v2 folder first (it lists Drive live and reads
// tags from CRATE_DIR, which must point at the TRIMMED audio so durations match).
//
// Everything is written to *-v2.json siblings. Nothing is swapped in. The cutover
// (rename the -v2 files over the originals + flip GOOGLE_DRIVE_FOLDER_ID + deploy)
// is a separate deliberate step so it can be inspected and reverted as one unit.
//
// Usage:  node --experimental-strip-types --no-warnings scripts/rekey-to-v2.mjs
// Env:    GOOGLE_API_KEY, V2_FOLDER_ID (default: the v2 folder created 2026-08-15)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = fileURLToPath(new URL("..", import.meta.url));
const DATA = path.join(REPO_ROOT, "src", "data");
const V2_FOLDER_ID = process.env.V2_FOLDER_ID || "1Y7QtljFoUOaoCAp78k2YrlPNwtIk6-Yo";

// tiny .env.local reader, same as the other scripts - never logs values
function loadEnvLocal() {
  const p = path.join(REPO_ROOT, ".env.local");
  if (!existsSync(p)) return;
  for (const line of readFileSync(p, "utf8").split(/\r?\n/)) {
    const m = /^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)\s*$/.exec(line);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}
loadEnvLocal();
const API_KEY = process.env.GOOGLE_API_KEY;
if (!API_KEY) { console.error("GOOGLE_API_KEY not set"); process.exit(1); }

/** List every file under a Drive folder (paged). Returns [{id,name,parent}]. */
async function listFolder(folderId) {
  const out = [];
  let pageToken;
  do {
    const u = new URL("https://www.googleapis.com/drive/v3/files");
    u.searchParams.set("q", `'${folderId}' in parents and trashed = false`);
    u.searchParams.set("fields", "nextPageToken,files(id,name,mimeType)");
    u.searchParams.set("pageSize", "1000");
    u.searchParams.set("key", API_KEY);
    if (pageToken) u.searchParams.set("pageToken", pageToken);
    const r = await fetch(u);
    if (!r.ok) throw new Error(`Drive list ${folderId}: HTTP ${r.status} ${await r.text()}`);
    const j = await r.json();
    out.push(...(j.files ?? []));
    pageToken = j.nextPageToken;
  } while (pageToken);
  return out;
}

// --- 1. old-id -> new-id via the OLD manifest's names ---
const oldManifest = JSON.parse(readFileSync(path.join(DATA, "crate-manifest.json"), "utf8"));
const oldIdByName = new Map(oldManifest.map((t) => [t.name, t.id]));

console.log(`listing v2 folder ${V2_FOLDER_ID} ...`);
const v2Files = await listFolder(V2_FOLDER_ID);
const v2Audio = v2Files.filter((f) => f.name.toLowerCase().endsWith(".mp3"));
const stemsFolder = v2Files.find((f) => f.name === "stems" && f.mimeType === "application/vnd.google-apps.folder");
console.log(`  v2: ${v2Audio.length} mp3s, stems/ ${stemsFolder ? "present" : "MISSING"}`);

const newIdByName = new Map(v2Audio.map((f) => [f.name, f.id]));
const idMap = new Map(); // old -> new
let unmatched = 0;
for (const [name, oldId] of oldIdByName) {
  const newId = newIdByName.get(name);
  if (newId) idMap.set(oldId, newId); else unmatched++;
}
console.log(`  id map: ${idMap.size} tracks re-keyed, ${unmatched} old names not found in v2`);

// --- 2. re-key the timeline files ---
function rekeyFile(name) {
  const src = path.join(DATA, `${name}.json`);
  if (!existsSync(src)) { console.log(`  ${name}: not present, skipped`); return; }
  const data = JSON.parse(readFileSync(src, "utf8"));
  const out = {};
  let hit = 0, miss = 0;
  for (const [k, v] of Object.entries(data)) {
    const bare = k.startsWith("drive:") ? k.slice(6) : k;
    const nid = idMap.get(bare);
    if (nid) { out[k.startsWith("drive:") ? `drive:${nid}` : nid] = v; hit++; }
    else { out[k] = v; miss++; } // keep as-is rather than lose it
  }
  const dst = path.join(DATA, `${name.replace(/-trimmed$/, "")}-v2.json`);
  writeFileSync(dst, JSON.stringify(out, null, 2));
  console.log(`  ${name.padEnd(26)} -> ${path.basename(dst).padEnd(26)} rekeyed=${hit} kept-old=${miss}`);
}
for (const f of ["loop-points-trimmed", "vocal-maps-trimmed", "cue-suggestions-trimmed"]) rekeyFile(f);

// --- 3. stem-manifest: local paths -> Drive ids under stems/<track dir>/ ---
if (!stemsFolder) {
  console.log("  stem-manifest: stems/ not uploaded yet — skipping (rerun after the stem upload)");
} else {
  const stemsSrc = JSON.parse(readFileSync(path.join(DATA, "stem-manifest.json"), "utf8"));
  const trackDirs = await listFolder(stemsFolder.id);
  const dirIdByName = new Map(trackDirs.filter((d) => d.mimeType === "application/vnd.google-apps.folder").map((d) => [d.name, d.id]));
  const out = {};
  let done = 0, noDir = 0, partial = 0;
  for (const [oldId, entry] of Object.entries(stemsSrc)) {
    const nid = idMap.get(oldId);
    if (!nid) continue;
    // stem values look like "htdemucs_6s/<track dir>/<stem>.mp3"
    const firstRel = Object.values(entry.stems)[0] ?? "";
    const trackDir = firstRel.split("/")[1];
    const dirId = trackDir ? dirIdByName.get(trackDir) : undefined;
    if (!dirId) { noDir++; continue; }
    const files = await listFolder(dirId);
    const fileIdByName = new Map(files.map((f) => [f.name, f.id]));
    const stems = {};
    let missing = 0;
    for (const [stem, rel] of Object.entries(entry.stems)) {
      const fid = fileIdByName.get(path.basename(rel));
      if (fid) stems[stem] = fid; else missing++;
    }
    if (missing) { partial++; continue; } // all-or-nothing, same rule as the player
    out[nid] = { ...entry, stems };
    done++;
    if (done % 25 === 0) console.log(`    stems: ${done} tracks resolved...`);
  }
  writeFileSync(path.join(DATA, "stem-manifest-v2.json"), JSON.stringify(out, null, 2));
  console.log(`  stem-manifest              -> stem-manifest-v2.json          resolved=${done} noDir=${noDir} partial=${partial}`);
}

console.log("\nWrote *-v2.json siblings. NOTHING swapped in. Cutover is a separate step.");
