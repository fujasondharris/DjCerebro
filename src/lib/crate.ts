// Pure Google Drive crate-listing logic (M5) shared by the /api/crate route
// (server, filters the raw Drive API response) and page.tsx (client, reads
// the shape back). UI/network-free by design — see scripts/check-crate-route.mjs.
import type { SeratoBeatgrid } from "./serato";

export interface DriveApiFile {
  id: string;
  name: string;
  mimeType: string;
  size?: string;
}

/** What the client sees per Drive file — `playable` gates whether "Add all from Drive" will fetch it (mp3-only; the soundtouchjs pipeline is mp3-tested, wav is skipped with a notice). */
export interface CrateTrackListing {
  id: string;
  name: string;
  size: number | null;
  mimeType: string;
  playable: boolean;
}

const MP3_MIME_TYPES = new Set(["audio/mpeg", "audio/mp3"]);

function isMp3(file: DriveApiFile): boolean {
  return MP3_MIME_TYPES.has(file.mimeType) || /\.mp3$/i.test(file.name);
}

function isAudioFile(file: DriveApiFile): boolean {
  return file.mimeType.startsWith("audio/") || /\.(mp3|wav)$/i.test(file.name);
}

export function toListing(file: DriveApiFile): CrateTrackListing {
  return {
    id: file.id,
    name: file.name,
    size: file.size != null ? Number(file.size) : null,
    mimeType: file.mimeType,
    playable: isMp3(file),
  };
}

/** Filters a raw Drive file list down to audio files (mp3 + wav) and marks which are playable (mp3 only) — non-audio files (folders, docs) are dropped entirely rather than shown-and-skipped. */
export function filterAudioFiles(files: DriveApiFile[]): CrateTrackListing[] {
  return files.filter(isAudioFile).map(toListing);
}

/**
 * Merges Drive API list pages (one `files[]` array per page, in fetch order)
 * into a single flat list, preserving order. The Drive v3 `files.list`
 * endpoint paginates (default page size 100, max 1000) — a folder with more
 * files than one page returns would silently truncate without this, since
 * the route must follow `nextPageToken` until it's absent and concatenate
 * every page's `files` before filtering. Pure so the merge itself is
 * checkable without a network call — see scripts/check-crate-route.mjs.
 */
export function mergeDrivePages(pages: DriveApiFile[][]): DriveApiFile[] {
  return pages.flat();
}

// ---------------------------------------------------------------------------
// Keyless fallback (M5 scope addendum) — when running keyless without a Google
// API key, the loader must also work without one. Precedence, resolved by
// resolveListingSource(): a real GOOGLE_API_KEY always wins (live, paginated
// Drive listing); no key falls back to a committed static manifest
// (src/data/crate-manifest.json, regenerated by the conductor via Drive MCP
// on request — "refresh the crate" — until a key is provided); no key AND no
// manifest is the original clean 500.
// ---------------------------------------------------------------------------

export type ListingSource = "live" | "manifest" | "none";

/** Pure precedence decision — no I/O, checkable without a real key or file. */
export function resolveListingSource(hasApiKey: boolean, hasManifest: boolean): ListingSource {
  if (hasApiKey) return "live";
  if (hasManifest) return "manifest";
  return "none";
}

/**
 * One entry in the committed manifest — id/name/size deliberately minimal
 * (no mimeType; mp3-ness is inferred from the filename, same as the live
 * Drive path's extension fallback). `bpm`/`key`/`durationSeconds`/`grid`
 * (M6.2 probe-storm fix, see CLAUDE_STATE.md) are filled in by
 * scripts/make-crate-manifest.mjs from a LOCAL file match (the local
 * Downloads\dj-crate mirror) — null/undefined when no local match was found
 * or the local file carried no tag, in which case the client falls back to
 * its normal Range-probe path for that one track, same as before this fix.
 */
export interface CrateManifestEntry {
  id: string;
  name: string;
  size?: number;
  bpm?: number | null;
  key?: string | null;
  durationSeconds?: number | null;
  grid?: SeratoBeatgrid | null;
}

export function manifestToListing(entries: CrateManifestEntry[]): CrateTrackListing[] {
  return entries.map((entry) => ({
    id: entry.id,
    name: entry.name,
    size: entry.size ?? null,
    mimeType: "audio/mpeg",
    playable: /\.mp3$/i.test(entry.name),
  }));
}

/** What a client needs to skip a network tag-probe for a Drive track it already has local tag data for — see buildManifestTagIndex(). */
export interface ManifestTrackTags {
  bpm: number | null;
  key: string | null;
  durationSeconds: number | null;
  grid: SeratoBeatgrid | null;
}

/**
 * True when at least one of bpm/key is known. A manifest (or already-in-crate)
 * entry with both null carries no usable tag data — e.g. a Drive filename
 * that didn't resolve to a local file during the manifest refresh — so the
 * caller should still fall back to a live probe for it rather than treating
 * "we checked and found nothing" the same as "we haven't checked yet".
 */
export function hasUsableTags(tags: { bpm: number | null; key: string | null } | null | undefined): boolean {
  return !!tags && (tags.bpm !== null || tags.key !== null);
}

/**
 * Indexes the committed manifest's tag data by Drive file id so a client can
 * look up "do we already know this track's bpm/key/grid" in O(1) without
 * scanning the whole manifest per track — see page.tsx's
 * handleAddAllFromDrive (M6.2 probe-storm fix). Deliberately independent of
 * resolveListingSource(): the manifest is consulted as a tag side-channel
 * here regardless of whether the crate LISTING itself came from this same
 * manifest or a live Drive API call (production runs "live" — see
 * CLAUDE_STATE.md — but the tag data below is still keyed by the same real
 * Drive file ids either way). Pure, no I/O — checkable without a real
 * manifest file, see scripts/check-crate-route.mjs.
 */
export function buildManifestTagIndex(entries: CrateManifestEntry[]): Map<string, ManifestTrackTags> {
  const index = new Map<string, ManifestTrackTags>();
  for (const entry of entries) {
    index.set(entry.id, {
      bpm: entry.bpm ?? null,
      key: entry.key ?? null,
      durationSeconds: entry.durationSeconds ?? null,
      grid: entry.grid ?? null,
    });
  }
  return index;
}

/**
 * Matches a Drive filename against a local-mirror directory listing: exact
 * match first, case-insensitive fallback second, null when neither hits.
 * Used by scripts/make-crate-manifest.mjs to find each Drive track's local
 * file for tag extraction — pure so the matching rule itself is checkable
 * without a real filesystem (see scripts/check-crate-route.mjs).
 */
export function matchLocalFilename(driveName: string, localNames: string[]): string | null {
  if (localNames.includes(driveName)) return driveName;
  const lower = driveName.toLowerCase();
  return localNames.find((name) => name.toLowerCase() === lower) ?? null;
}

/**
 * The keyless download path (`drive.google.com/uc?export=download`) can
 * return HTTP 200 with an HTML body instead of file bytes — Drive's
 * "can't scan this file for viruses" interstitial, or a not-shared/removed
 * file's error page. Flags a response's Content-Type as suspicious so the
 * download route can surface an honest per-track error instead of handing
 * the browser an HTML page disguised as an MP3. Deliberately permissive
 * otherwise (missing header, `application/octet-stream`, etc. all pass) —
 * only text/* and anything mentioning "html" is flagged.
 */
export function isSuspiciousDownloadContentType(contentType: string | null): boolean {
  if (!contentType) return false;
  const lower = contentType.toLowerCase();
  return lower.includes("html") || lower.startsWith("text/");
}

/**
 * Treats an empty/whitespace-only GOOGLE_API_KEY the same as absent.
 * `process.env.GOOGLE_API_KEY` can come back `""` (a Vercel env var that's
 * set but left blank) or a stray whitespace typo — both are JS-truthy as a
 * bare string but useless as a real key, and either would previously fall
 * through to a broken keyed URL (`...&key=`) or a Drive-rejected whitespace
 * key instead of the working keyless path. Shared by both crate routes
 * (M6.2 hardening) so there's exactly one definition of "usable key".
 */
export function isUsableGoogleApiKey(key: string | null | undefined): boolean {
  return typeof key === "string" && key.trim().length > 0;
}

/**
 * True when the download proxy's upstream response looks like Google's
 * abuse/rate-limit block (a 403 whose body is the "Sorry..." HTML
 * interstitial) rather than a real, non-retryable error (bad id, permission
 * denied, quota — these come back as JSON from the keyed googleapis.com
 * path and should NOT be retried). The download route retries exactly once
 * on this, never on anything else — see /api/crate/[id]/route.ts.
 */
export function shouldRetryDriveDownload(status: number, bodySample: string, contentType: string | null): boolean {
  if (status !== 403) return false;
  return isSuspiciousDownloadContentType(contentType) || /sorry/i.test(bodySample);
}

// ---------------------------------------------------------------------------
// Partial-fetch (Range) support for the lazy-crate architecture — the
// download proxy (/api/crate/[id]) forwards a client Range header upstream
// so the client can fetch just the first ~256KB of a track for tag parsing
// (see src/lib/crate-lazy.ts) instead of the whole file. Both Drive paths
// (googleapis.com alt=media and the keyless drive.google.com/uc) generally
// honor Range and reply 206 with Content-Range when they do; a 200 with the
// full body is also a valid (if less efficient) response the proxy must
// pass through unchanged rather than assume 206. Split out as pure functions
// so this is checkable without a network call — see
// scripts/check-crate-route.mjs.
// ---------------------------------------------------------------------------

/** Builds the headers to forward a client's Range request to the Drive upstream fetch. Returns {} (no Range forwarded) when the client didn't send one — the proxy's original whole-file behavior. */
export function buildUpstreamRangeHeaders(clientRangeHeader: string | null): HeadersInit {
  return clientRangeHeader ? { Range: clientRangeHeader } : {};
}

/** Shapes the proxy's own response headers from the upstream response's headers — passes through Content-Range/Content-Length when present (so a 206 partial response looks like a real one to the client) alongside the fixed audio/mpeg Content-Type. Takes plain strings/nulls, not Response/Headers objects, so it's checkable without a network call. */
export function buildProxyResponseHeaders(upstream: {
  contentRange?: string | null;
  contentLength?: string | null;
}): Record<string, string> {
  const headers: Record<string, string> = { "Content-Type": "audio/mpeg", "Accept-Ranges": "bytes" };
  if (upstream.contentRange) headers["Content-Range"] = upstream.contentRange;
  if (upstream.contentLength) headers["Content-Length"] = upstream.contentLength;
  return headers;
}
