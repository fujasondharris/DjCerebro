// Google Drive crate loader — M5 Deliverable 1. Lists audio files in a
// shared Drive folder via the Drive v3 REST API (API key, no OAuth). Browser
// fetch of googleapis.com is CORS-blocked, so this proxies server-side; the
// actual filtering/shaping logic lives in src/lib/crate.ts so it's checkable
// without a real key or network (see scripts/check-crate-route.mjs). Mirrors
// /api/dj's shape: missing GOOGLE_API_KEY -> clean 500 {"error": ...}.
import { NextResponse } from "next/server";
import { checkPasscode } from "@/lib/passcode";
import {
  filterAudioFiles,
  mergeDrivePages,
  manifestToListing,
  resolveListingSource,
  isUsableGoogleApiKey,
  type DriveApiFile,
  type CrateManifestEntry,
} from "@/lib/crate";
import manifestJson from "@/data/crate-manifest.json";

export const runtime = "nodejs";

// Keyless fallback manifest — see src/lib/crate.ts's resolveListingSource()
// doc comment. Regenerated by the conductor (Claude, via Drive MCP) on
// request ("refresh the crate") until a GOOGLE_API_KEY is configured; currently
// empty because the "DJ Supermercado Crate" folder was just created.
const MANIFEST: CrateManifestEntry[] = manifestJson as CrateManifestEntry[];

// Max page size the Drive v3 files.list endpoint accepts. Requesting the max
// up front minimizes round trips; still follows nextPageToken below in case
// the folder ever exceeds this in one page.
const DRIVE_PAGE_SIZE = 1000;

async function fetchAllDriveFiles(folderId: string, apiKey: string): Promise<DriveApiFile[]> {
  const pages: DriveApiFile[][] = [];
  let pageToken: string | undefined;

  do {
    const url = new URL("https://www.googleapis.com/drive/v3/files");
    url.searchParams.set("q", `'${folderId}' in parents`);
    url.searchParams.set("key", apiKey);
    url.searchParams.set("fields", "nextPageToken, files(id,name,mimeType,size)");
    url.searchParams.set("pageSize", String(DRIVE_PAGE_SIZE));
    if (pageToken) url.searchParams.set("pageToken", pageToken);

    const upstream = await fetch(url.toString());
    if (!upstream.ok) {
      const text = await upstream.text().catch(() => "");
      throw new Error(`HTTP ${upstream.status} ${text.slice(0, 200)}`);
    }
    const json = (await upstream.json()) as { files?: DriveApiFile[]; nextPageToken?: string };
    pages.push(Array.isArray(json.files) ? json.files : []);
    pageToken = json.nextPageToken;
  } while (pageToken);

  return mergeDrivePages(pages);
}

export async function GET(request: Request) {
  const passcodeCheck = checkPasscode(process.env.DJ_PASSCODE, request.headers.get("x-dj-passcode"));
  if (!passcodeCheck.ok) {
    return NextResponse.json({ error: passcodeCheck.error }, { status: 401 });
  }

  const apiKey = process.env.GOOGLE_API_KEY;
  const source = resolveListingSource(isUsableGoogleApiKey(apiKey), Array.isArray(MANIFEST));

  if (source === "none") {
    return NextResponse.json(
      {
        error:
          "GOOGLE_API_KEY is not set on the server and no crate-manifest.json fallback exists. Add a key to .env.local, or ask the conductor to refresh the crate manifest.",
      },
      { status: 500 }
    );
  }

  if (source === "manifest") {
    return NextResponse.json({ tracks: manifestToListing(MANIFEST), source: "manifest" });
  }

  // source === "live"
  const folderId = process.env.GOOGLE_DRIVE_FOLDER_ID;
  if (!folderId) {
    return NextResponse.json(
      { error: "GOOGLE_DRIVE_FOLDER_ID is not set on the server. Set it to your Drive crate folder's id." },
      { status: 500 }
    );
  }
  try {
    const files = await fetchAllDriveFiles(folderId, apiKey!);
    return NextResponse.json({ tracks: filterAudioFiles(files), source: "live" });
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return NextResponse.json({ error: `Drive list failed: ${message}` }, { status: 502 });
  }
}
